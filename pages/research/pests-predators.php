  <section class="dsection">
    <h2 class="dsection__h">Muga: uzi fly management</h2>
    <p>The uzi fly peaks from November to April and is worst in Chotua (March&ndash;April),
    striking fourth and fifth instar larvae and then damaging cocoons at harvest &mdash;
    destroying the seed cocoons on which Jethua depends. Reported crop losses run 20&ndash;40 %.</p>
    <ul class="dlist">
      <li><strong>How it works:</strong> the gravid female lays on the dorsal and dorso-lateral
      integument; maggots bore in and feed on internal tissue; a heavy fourth-instar infestation
      means the worm never spins. Mature maggots exit and pupate in the field or, if infested
      cocoons are carried in, inside the grainage hall.</li>
      <li><strong>Physical exclusion first:</strong> a properly erected and maintained nylon net
      remains the primary defence.</li>
      <li><strong>Sanitation:</strong> collect and destroy infested larvae and cocoons; never
      carry suspect cocoons into the grainage.</li>
      <li><strong>Biological control:</strong> <em>Nesolynx thymus</em> (Eulophidae), a gregarious
      pupal endoparasitoid, is host-specific, harmless to the silkworm and can be mass-multiplied
      and released around rearing fields. <em>Exoristobia philippinensis</em> occurs locally in
      the same role.</li>
      <li><strong>Chemical control is largely closed off:</strong> the muga silkworm is unusually
      sensitive to pesticides.</li>
    </ul>
    <div class="dnote">
      Because chemical control is effectively unavailable, uzi management in muga is a net,
      sanitation and biocontrol problem &mdash; there is no rescue treatment once a crop is
      infested. The institute&rsquo;s 2009 biological control package raises cocoon yield by 30 %
      in the Jarua and Chotua crops at a benefit&ndash;cost ratio of 2.03 : 1.
    </div>
  </section>

