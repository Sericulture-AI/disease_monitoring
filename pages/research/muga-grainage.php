          <tr><th>Emergence</th><td>About two weeks after cocoon formation; males emerge ahead of females. Hold the hall at 26&ndash;28 &deg;C. Fresh moths sit motionless 1&ndash;2 hours and must not be disturbed.</td></tr>
          <tr><th>Sorting</th><td>Reject deformed, darkened or weak moths before pairing.</td></tr>
          <tr><th>Pairing</th><td>Equal numbers of males and females in trays or cages by about 16.00 hours. Allow at least six hours before decoupling. Females emerging in the evening usually do not mate that night. If males are short, reuse decoupled males after 2&ndash;3 hours rest.</td></tr>
          <tr><th>Tying</th><td>Hold the coupled female by the right hind wing and tie her to the <em>kharika</em> &mdash; a straw or twig bundle about 8 inches long &mdash; with cotton thread.</td></tr>
          <tr><th>Laying</th><td>Three days only. A muga moth would lay over 6&ndash;7 days in the wild; limiting to three keeps hatching uniform and excludes disease from weak late-hatched larvae.</td></tr>
