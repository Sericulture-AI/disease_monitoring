    <h2 class="dsection__h">Seed cocoon selection and preservation</h2>
    <ul class="dlist">
      <li>Larvae uniform in size through rearing; cocoons taken from the peak ripening date
      (<em>bhor pok</em>), compact and uniform.</li>
      <li><strong>Muga:</strong> female &ge; 6.0 g, male &ge; 4.0 g. <strong>Eri:</strong>
      female &ge; 3.0 g, male &ge; 2.5 g.</li>
      <li>Transport in cooler hours in shelved bamboo baskets so cocoons neither overlap nor
      bruise.</li>
      <li>Preserve in a cocoon cage in a single layer or as a garland, cool and well ventilated,
      at 27&ndash;29 &deg;C and 70&ndash;80 % RH.</li>
    </ul>
  </section>

