  <section class="dsection">
    <h2 class="dsection__h">Brushing and crop management</h2>
    <ul class="dlist">
      <li><strong>Brushing:</strong> spread tender leaves over newly hatched larvae so they
      settle; transfer with the leaves early morning &mdash; away from sun in summer, towards it
      in winter; avoid overcrowding.</li>
      <li><strong>Trunk banding:</strong> wrap each trunk to 2&ndash;2.5 ft with polythene or
      banana sheath to stop larvae descending and ants ascending.</li>
      <li><strong>Age-wise rearing:</strong> light pruning or defoliation three months ahead
      supplies tender leaf to the third instar at about one dfl per young plant; late-age worms
      go onto semi-mature to mature foliage.</li>
      <li><strong>Stocking:</strong> 1&ndash;1.5 dfls on a 3&ndash;7 year old plant; 3&ndash;4
      dfls above 7 years; 2,000 dfls per hectare per year in two seasons.</li>
      <li><strong>Handling:</strong> transfer by cutting twigs; use bamboo forceps for dead and
      diseased larvae; keep 5 % bleaching powder solution and fresh water at the site for hand
      sanitation.</li>
      <li><strong>Sanitation:</strong> bury diseased, dead and undersized larvae in a pit 1.5 ft
      deep away from the field, dusted with 9:1 slaked lime and bleaching powder.</li>
      <li><strong>Seasonal care:</strong> lift the net by day in summer and close it before dusk;
      use smoke morning and evening in winter.</li>
      <li><strong>Maturity:</strong> ripe larvae crawl down the trunk of their own accord and
      must be collected promptly.</li>
    </ul>
  </section>

